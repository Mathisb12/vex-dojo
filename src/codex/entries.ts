// ─── Le Codex — référence VEX en français ────────────────────────────────────
//
// Il n'existe pas de documentation VEX en français. C'est la raison d'être de
// cette section.
//
// Toutes les signatures viennent de Houdini lui-même : `vcc --list-context-json=sop`
// sur Houdini 22.0.429, pas d'une recopie à la main. Les surcharges les plus
// utiles ont été retenues, pas les 40 variantes de `point()`.
//
// `run` dit si le bac à sable de ce site sait exécuter la fonction. Beaucoup des
// fonctions les plus utiles en production touchent à la vraie géométrie
// (création de points, voisinage, intersection) et ne tournent pas ici — elles
// restent documentées, parce qu'un artiste a besoin de les connaître.

export type CodexCat =
  | 'math' | 'trig' | 'remap' | 'vector' | 'noise' | 'attrib'
  | 'geo' | 'near' | 'surface' | 'xform' | 'param' | 'data' | 'volume'

export interface CodexFn {
  name: string
  /** Signature exacte, telle que le compilateur VEX la déclare. */
  sig: string
  cat: CodexCat
  /** Ce que ça fait. */
  fr: string
  /** Quand y penser, concrètement. */
  when: string
  /** Exécutable dans le bac à sable de ce site ? */
  run: boolean
  /** Court exemple ; quand `run` est vrai, il tourne tel quel. */
  ex?: string
  see?: string[]
}

